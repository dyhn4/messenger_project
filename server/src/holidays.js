const DAY_MS = 86400000;

/**
 * [fromMs, toMs) 구간과 하루라도 겹치는 공휴일. 종일 일정 표현(날짜를 UTC 자정으로 본 epoch ms)과
 * 같은 방식으로 비교한다 — 공휴일은 "그 날짜"라서 시간대가 끼어들 자리가 없다.
 * 반환: [{ date, name, startMs, endMs }] (startMs = 그 날짜의 UTC 자정, endMs = 다음 날 UTC 자정).
 */
export function holidaysInRange(fromMs, toMs) {
  const result = [];
  for (const h of HOLIDAYS) {
    const startMs = Date.parse(`${h.date}T00:00:00Z`);
    const endMs = startMs + DAY_MS;
    if (startMs < toMs && endMs > fromMs) result.push({ ...h, startMs, endMs });
  }
  return result;
}
